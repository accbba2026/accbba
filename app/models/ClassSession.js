// app/models/ClassSession.js
import mongoose from "mongoose";

const classSessionSchema = new mongoose.Schema(
  {
    date: { type: String, required: true }, // "2025-01-15"
    semester: {
      type: String,
      required: true,
      enum: ["1st", "2nd", "3rd", "4th", "5th", "6th", "7th", "8th"],
    },
    major: {
      type: String,
      // null for 1st–6th semester
      enum: [
        "finance & banking",
        "marketing",
        "management",
        "accounting",
        null,
      ],
      default: null,
    },
    inputBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    status: {
      type: String,
      enum: ["held", "cancelled"],
      default: "held",
    },
    note: { type: String },
    // ✅ NEW: distinguishes manually-created (7/8) from auto-created (1–6)
    isAutoGenerated: { type: Boolean, default: false },
  },
  { timestamps: true }
);

// One session per date + semester + major.
// `major: null` collides with itself just like a normal value (MongoDB indexes null),
// so 1st–6th will still enforce "one auto-session per date".
classSessionSchema.index(
  { date: 1, semester: 1, major: 1 },
  { unique: true }
);
classSessionSchema.index({ createdAt: -1 });

const ClassSession =
  mongoose.models.ClassSession ||
  mongoose.model("ClassSession", classSessionSchema);

export default ClassSession;